POSTS_DIR = Path(__file__).resolve().parent.parent / "_posts"

RE_CATEGORIES = re.compile(r"^categories\s*:")
RE_TAGS = re.compile(r"^tags\s*:")


def build_line(key: str, values, comment: str, eol: str) -> str:
    """拼出 categories / tags 这一行（保留原文件的行尾符）。"""
    return "{}: [{}]  # {}{}".format(key, ", ".join(values), comment, eol)


def process(dry_run: bool = False):
    # ---------- 第一步：自检 ----------
    if not POSTS_DIR.is_dir():
        sys.exit("找不到 _posts 目录：{}".format(POSTS_DIR))

    all_files = {p.name for p in POSTS_DIR.glob("*.md")}
    missing = sorted(set(MAP) - all_files)
    uncovered = sorted(all_files - set(MAP))
    if missing:
        sys.exit("映射表里有 {} 个文件名在 _posts 中不存在，已中止：\n  {}".format(
            len(missing), "\n  ".join(missing)))
    if uncovered:
        print("⚠ 有 {} 篇文章未纳入映射表，保持原样：".format(len(uncovered)))
        for name in uncovered:
            print("   - " + name)
        print()

    # ---------- 第二步：逐篇改写 ----------
    changed = 0
    for name in sorted(MAP):
        cats, tags = MAP[name]
        path = POSTS_DIR / name
        raw = path.read_text(encoding="utf-8")
        lines = raw.splitlines(True)

        hit_c = hit_t = 0
        for i, line in enumerate(lines):
            # 只在前 20 行（front matter 区）里找，避免误伤正文里的同名文字
            if i > 20:
                break
            eol = "\r\n" if line.endswith("\r\n") else ("\n" if line.endswith("\n") else "")
            body = line.rstrip("\r\n")
            if RE_CATEGORIES.match(body):
                lines[i] = build_line("categories", cats,
                                      "一级分类, 二级分类（固定两级，从左到右）", eol)
                hit_c += 1
            elif RE_TAGS.match(body):
                lines[i] = build_line("tags", tags,
                                      "标签 2~4 个，英文逗号隔开", eol)
                hit_t += 1
            if hit_c and hit_t:
                break

        if not (hit_c and hit_t):
            print("⚠ 跳过（没找到 categories 或 tags 行）：" + name)
            continue

        new_raw = "".join(lines)
        if new_raw != raw:
            changed += 1
            if not dry_run:
                path.write_text(new_raw, encoding="utf-8")

        flag = "预览" if dry_run else "已改"
        print("[{}] {:<28} {}/{}  {}".format(
            flag, name, cats[0], cats[1], " ".join("#" + t for t in tags)))

    print("\n共 {} 篇，实际改写 {} 篇（{}）。".format(
        len(MAP), changed, "预演模式，未写入磁盘" if dry_run else "已写入磁盘"))


if __name__ == "__main__":
    process(dry_run="--dry-run" in sys.argv)
