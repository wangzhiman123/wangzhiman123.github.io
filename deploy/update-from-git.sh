#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  update-from-git.sh —— 从 Git 拉取最新代码并发布
#  （等价于 publish.sh --from-git，保留这个别名方便记忆）
#
#  一句话概括：这是一个"一句话更新网站"的简易入口。
#  您在电脑上写完文章推到 GitHub 之后，在服务器上跑一下它，
#  网站就会更新到最新内容。
#
#  【它为什么这么短？】
#  因为它自己不做任何实际工作，只是把活转交给 publish.sh。
#  存在的价值纯粹是"取个好记的名字"——
#  publish.sh 带参数 --from-git 不太直观，而 update-from-git.sh 一看就知道干什么。
#  这种"只做转发的短脚本"叫别名脚本，是很好的习惯：
#  真正复杂的逻辑只有一份（在 publish.sh 里），维护起来不容易出错。
#
#  用法：bash update-from-git.sh
#
#  【和另外两个脚本的区别，别搞混】
#    · publish.sh            —— 核心逻辑，直接用服务器现有代码构建发布；
#    · update-from-git.sh    —— 先拉最新代码再构建发布（就是本文件）；
#    · views-refresh.sh      —— 专给定时任务用，先更新浏览量数据再发布。
# ============================================================
set -euo pipefail
# 脚本安全模式（出错就停、变量必须已定义、管道任一环节出错即失败）。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 取得本脚本所在文件夹绝对路径，
# 这样才能准确找到旁边那个 publish.sh（不管您从哪个目录运行本脚本）。
exec bash "$HERE/publish.sh" --from-git
# 【核心就这一行】把工作完全交给发布脚本，并告诉它"先拉最新代码"。
# 几个细节值得说明：
#   exec —— 表示"用这个新命令替换当前进程"，而不是再开一个新的子进程。
#           效果上等同于"本脚本后半段没有内容了，直接变成在跑 publish.sh"。
#           好处：不会多留一层进程，输出和退出状态也更干净直接。
#   --from-git —— 这个参数就是开关，让 publish.sh 知道要先执行同步动作
#           （去 GitHub 拉最新代码，再构建发布）。
#           对应 publish.sh 里的第 0 步："从 Git 拉取最新代码"。
# 所以本文件最终实现的完整流程是：
#   GitHub 拉取最新代码 → 检查环境 → 安装组件 → 构建网站 → 自检 → 切换上线 → 清理旧版本。
