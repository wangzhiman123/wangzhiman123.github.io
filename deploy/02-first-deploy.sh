#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  02-first-deploy.sh —— 首次部署（从 GitHub 拉源码 + 首次构建发布）
#
#  一句话概括：这是"第一次把网站搬上服务器并点亮"的脚本。
#  它会先把您的博客源码弄到服务器上，检查关键文件齐不齐，
#  然后执行一次正式的构建发布，让网站真正跑起来。
#
#  用法（服务器上，root）：
#      cd /opt/site/src/deploy
#      bash 02-first-deploy.sh
#
#  如果源码已经在 $SRC_DIR（例如你用 deploy-aliyun.bat 上传过了），
#  这个脚本会自动跳过 clone，直接进入构建。
#  —— 这一点很贴心：它不关心源码是怎么来的，只要有就直接用，
#     所以"从 GitHub 拉"和"从本地上传"两条路都能走同一个脚本。
# ============================================================
set -euo pipefail
# 脚本安全模式（出错就停、变量必须已定义、管道任一环节出错即失败）。
# 详细说明见 01-server-init.sh 里的注释。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 取得本脚本所在的文件夹绝对路径，存进 HERE，保证不管从哪运行都能找到旁边的文件。

CONF="$HERE/config.env"
[[ -f "$CONF" ]] || { echo "❌ 找不到 $CONF，请先 cp config.env.example config.env 并填写"; exit 1; }
# 检查配置文件是否存在，不存在就提示并退出。
# 这一行把"判断 + 提示 + 退出"三个动作压缩成一行：
#   [[ -f ... ]] || { ... } 的意思是"如果文件不存在，就执行后面大括号里的内容"。
source "$CONF"
# 读取配置内容，让 DOMAIN、SRC_DIR、REPO_URL 等变量可用。

log() { echo -e "\n\033[1;34m▶ $*\033[0m"; }
# 打印蓝色步骤标题的小工具。
ok()  { echo -e "\033[1;32m✅ $*\033[0m"; }
# 打印绿色成功提示的小工具。

# ------------------------------------------------------------
# ================== 第 1 步：把源码弄到服务器 ==================
log "1/3  准备源码到 $SRC_DIR"
if [[ -f "$SRC_DIR/Gemfile" ]]; then
  # 情况一：源码目录里已经有 Gemfile（这是项目的组件清单文件，
  # 有它就说明源码是完整的），说明之前已经准备好了。
  ok "源码已存在，跳过 clone"
  # 直接跳过，不重复下载。这叫"幂等"——同一个脚本重复运行也不会出问题。
elif [[ -d "$SRC_DIR/.git" ]]; then
  # 情况二：目录里已经有 .git 文件夹，说明这里是个 Git 仓库，
  # 但缺少 Gemfile，可能是下载没完成或者被人手工改动过。
  ok "已是 git 仓库，执行同步"
  git -C "$SRC_DIR" fetch --all --prune
  # 从 GitHub 拉回最新的版本信息。
  #   -C "$SRC_DIR" = 到指定目录里去执行这个 git 命令；
  #   fetch        = 只下载最新的记录，先不合并；
  #   --all        = 所有分支都拉；
  #   --prune      = 把远端已经删掉的分支信息也一并清理掉，保持整齐。
  git -C "$SRC_DIR" reset --hard "origin/${REPO_BRANCH}"
  # 强制把本地文件恢复成"远程仓库最新版"的样子。
  # 【注意】--hard 会丢弃本地未提交的修改。
  # 在这里是合理的：服务器上的源码应该始终和 GitHub 保持一致，
  # 您所有的写作和修改都该在本机做、再推上去，而不是直接在服务器上改。
  # 这样能保证代码只有一个权威来源，不会出现"两边不一样、到底以谁为准"的混乱。
else
  # 情况三：什么都没有，需要从头下载。
  echo "   正在从 GitHub 克隆（首次约 10~60 秒）…"
  mkdir -p "$(dirname "$SRC_DIR")"
  # 先确保上级目录存在，否则下面没法建目录。
  # 目录可能已被创建为空目录，git clone 要求目标为空
  rmdir "$SRC_DIR" 2>/dev/null || true
  # 【这一步很关键，别忽略】git clone 硬性要求"目标文件夹必须是空的或不存在"。
  # 而 01-server-init.sh 已经把 $SRC_DIR 建出来了（虽然里面是空的），
  # 有些 git 版本仍会拒绝。所以这里试着把这个空目录删掉。
  # 2>/dev/null 表示"删不掉也别显示报错"，|| true 表示"失败也不中断"。
  # 注意用的是 rmdir 不是 rm：rmdir 只能删空目录，
  # 【重要】就算这个目录里真有东西，rmdir 也不会删掉它，安全性更高。
  git clone --branch "$REPO_BRANCH" "$REPO_URL" "$SRC_DIR"
  # 从 GitHub 下载代码。
  #   --branch 指定下载哪个分支（本项目是 main）；
  #   后面依次是"仓库地址"和"下载到哪个目录"。
  ok "克隆完成"
fi

# ------------------------------------------------------------
# ================ 第 2 步：检查关键文件是否齐全 ================
log "2/3  检查关键文件"
for f in _config.yml Gemfile _posts; do
  # 挨个检查这三个最要紧的东西：
  #   _config.yml —— 网站总配置，缺了就不知道网站叫什么、怎么建；
  #   Gemfile     —— 项目组件清单，缺了装不了运行环境；
  #   _posts      —— 文章文件夹，缺了就算能建站也是一片空白。
  if [[ -e "$SRC_DIR/$f" ]]; then
    # -e 表示"这个文件或目录存在"。
    echo "   ✅ $f"
  else
    echo "   ❌ 缺少 $f —— 源码可能不完整"
    exit 1
    # 立刻停止，不让它带着残缺的源码去构建，
    # 否则会浪费好几分钟最后构建失败，而且报错信息很难看懂。
  fi
done

# ------------------------------------------------------------
# ==================== 第 3 步：正式发布 ====================
log "3/3  执行发布（构建 → 自检 → 切换）"
bash "$HERE/publish.sh"
# 【关键衔接】把发布这件复杂的事交给专门的那个脚本来做。
# 也就是按照固定的三步走：
#   构建 —— 把文章编译成网页；
#   自检 —— 检查生成的网页有没有问题；
#   切换 —— 把网站切换到新版本。
# 【为什么拆成单独一个脚本？】因为以后每次更新网站也要用同样的流程，
# 所以把这段逻辑独立出来复用，日常更新也调用它。（见 deploy/publish.sh）

echo
ok "首次部署完成。下一步：bash $HERE/03-https.sh"
# 打印下一步该做什么。按顺序往下走，下一步是给网站装上 HTTPS 加密证书。
