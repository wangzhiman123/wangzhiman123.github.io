#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  01-server-init.sh —— 服务器初始化（全新 ECS 上只需跑一次）
#
#  一句话概括：这是"给新服务器做开荒保洁"的脚本，只需在最开始跑一次。
#  它会把一台刚买来、空荡荡的服务器，改造成能放网站的环境。
#
#  做什么：设置时区 → 安装 Nginx/Git/Ruby/Python → 建目录 → 写 Nginx 配置
#
#  用法（在服务器上，用 root）：
#      cd /opt/site/src/deploy
#      cp config.env.example config.env
#      vi config.env                 # 改 DOMAIN / LE_EMAIL
#      bash 01-server-init.sh
#
#  【小白必读：这三条命令分别是什么意思？】
#    · cp A B   —— 复制文件。把"配置模板"复制成"真正的配置文件"，方便您在上面改。
#      为什么要有这一步？因为模板是通用的、不含您的信息；复制一份出来改，
#      以后升级还能对照模板看到原来长什么样。
#    · vi config.env —— 用 vi 这个自带的文本编辑器打开配置文件来修改。
#      在 vi 里怎么操作：按 i 键进入编辑 → 用方向键移动、打字修改 →
#      改完按 Esc 键 → 输入 :wq 然后回车（w 是保存、q 是退出）。
#    · bash 脚本名 —— 运行这个脚本。
#  【术语解释】root = Linux 系统的最高权限账号，相当于"管理员"，
#  安装软件、修改系统设置都需要它。
# ============================================================
set -euo pipefail
# 【这一行非常重要，建议不要删】它是脚本的"安全模式开关"，三个字母合起来的作用：
#   -e = 任何一步出错就立刻停止，不要硬着头皮往下跑。
#        好处：避免"装软件失败但脚本继续跑"，最后留下一堆半成品，越修越乱。
#   -u = 用到没定义的变量时报错。
#        好处：防止因为变量名写错，导致脚本误删了错误的目录（属于关键防护）。
#   -o pipefail = 管道里任何一个环节出错都算整个失败。
#        管道就是"把前一个命令的输出喂给后一个命令"的写法。
# 简单说：这一行让脚本"出错就停、不留隐患"，是写自动化脚本的好习惯。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 算出"本脚本所在的文件夹路径"，存进 HERE。
# 拆开读：
#   ${BASH_SOURCE[0]} 是"本脚本的文件路径"；
#   dirname ... 取它所在的文件夹（去掉文件名）；
#   cd ... && pwd 进入那个文件夹并打印出完整路径。
# 【为什么要这么绕？】为了得到"绝对路径"。这样无论您从哪个目录运行脚本，
# 它都能准确找到旁边的配置文件，不会因为当前目录不同而找不到。

CONF="$HERE/config.env"
# 配置文件的完整路径（就在脚本旁边）。

if [[ ! -f "$CONF" ]]; then
  echo "❌ 找不到配置文件：$CONF"
  echo "   请先执行： cp config.env.example config.env && vi config.env"
  exit 1
fi
# 检查配置文件是否存在。不存在就打印提示并退出。
# 【为什么先检查？】因为后面要读取里面的域名、目录等信息，
# 缺了它脚本根本没法工作，早点明确报错比跑到一半出错更容易排查。

# shellcheck disable=SC1090
source "$CONF"
# 把配置文件里的内容"读进来"，让里面定义的 DOMAIN、WEB_ROOT 等
# 变成脚本可以使用的变量。source 就是"读取并立即执行这个文件"的意思。
# 上面那行 # shellcheck ... 是给代码检查工具看的忽略说明，不影响运行。

log() { echo -e "\n\033[1;34m▶ $*\033[0m"; }
# 定义一个打印"步骤标题"的小工具。
#   \n = 先空一行
#   \033[1;34m ... \033[0m = 把中间的文字显示成"亮蓝色"
# 用法：log "开始安装"，屏幕上就会看到一行亮蓝色的"▶ 开始安装"。
# 【可DIY修改】想换颜色，把 34（蓝）改成 32（绿）、31（红）、33（黄）等。

ok()  { echo -e "\033[1;32m✅ $*\033[0m"; }
# 定义"成功提示"的打印工具，显示成绿色带 ✅ 符号。

warn(){ echo -e "\033[1;33m⚠️  $*\033[0m"; }
# 定义"警告提示"的打印工具，显示成黄色带 ⚠️ 符号。

if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
  echo "❌ 请用 root 运行： sudo bash $0"
  exit 1
fi
# 【权限检查】确认当前是"管理员身份"在运行脚本，不是就拒绝执行。
# 拆开读：
#   ${EUID:-$(id -u)} = 取当前用户编号；EUID 拿不到就用 id -u 命令再取一次；
#                       最高权限账号 root 的编号是 0。
#   -ne 0 = 不等于 0，也就是"不是 root"。
# 为什么要检查？因为下面要安装软件、改系统设置，普通账号没有这些权限，
# 与其跑到一半不停报"权限不足"，不如一开始就说清楚。
# 【怎么解决？】在命令前面加 sudo，变成： sudo bash 01-server-init.sh
#   sudo 的意思就是"请以管理员身份执行"，系统可能会要求您输入密码。

if [[ -z "${DOMAIN:-}" || "$DOMAIN" == "2019527.xyz" && "${LE_EMAIL:-}" == *"请改"* ]]; then
  warn "请确认 config.env 里的 DOMAIN / LE_EMAIL 已改成你自己的。"
fi
# 【防呆提醒】检查配置文件是不是还没改过。
# 拆开读：
#   -z "${DOMAIN:-}"        = 域名是空的（-z 表示"长度为 0"）；
#   "$DOMAIN" == "..."     = 域名还是模板里的示例值没换；
#   "${LE_EMAIL:-}" == *"请改"* = 邮箱那一栏还写着"请改"之类的提示文字。
# 命中任一情况就提醒一句——但不强制中止，因为万一您就是想先用示例域名试试呢。
# ⚠️ 正式上线前一定要把这两项换成自己的，否则后续申请 HTTPS 证书会失败。

# ------------------------------------------------------------
# ==================== 第 1 步：设置时区 ====================
log "1/7  设置时区为 Asia/Shanghai（保证文章日期正确）"
timedatectl set-timezone Asia/Shanghai
# 把服务器时间改成北京时间。
# 【为什么必须做？】服务器默认可能是 UTC（世界标准时间，比北京晚 8 小时）。
# 如果不改，晚上 8 点发的文章可能会被记成当天中午 12 点，
# 甚至显示成前一天，日期全都错位。
date
# 打印当前时间，让您确认一下改成功了没有（看到的应该是北京时间）。

# ------------------------------------------------------------
# ==================== 第 2 步：安装所需软件 ====================
log "2/7  更新系统并安装依赖（这一步最慢，约 2~5 分钟）"
export DEBIAN_FRONTEND=noninteractive
# 关掉安装过程中的"交互提问"。
# 【为什么要关？】有些软件安装时会弹出蓝色界面问您"是否替换配置文件"，
# 需要按键盘选择。自动化脚本没人去按，就会一直卡在那里不动。
# 关掉之后它就会自动选择默认答案，一路跑完。
export 的意思是把设置推广给后续所有命令使用。

apt-get update -y
# 刷新"软件商店的目录"——告诉系统现在有哪些可安装的软件、都是什么版本。
# 装任何新软件之前都应该先做这一步，否则可能装到旧版本或找不到。

apt-get upgrade -y
# 把系统里已装的软件更新到最新版（通常带上安全补丁）。
# 【可DIY修改】想加快首次部署速度，可以把这一行前面加 # 注释掉。
# 但建议首次还是跑一下，安全性更好。

apt-get install -y \
  nginx git curl unzip vim ca-certificates rsync \
  build-essential ruby-full zlib1g-dev libffi-dev \
  python3 python3-pip fail2ban
# 安装下面这些软件，逐个说明它们各自的作用（新手看这份清单就够了）：

#   nginx         —— 网站服务器软件。可以理解为"网站的传达室"：
#                    访客来访问时，由它把网页文件递给对方。
#   git           —— 版本管理工具，用来从 GitHub 下载和更新代码。
#   curl          —— 命令行下的小工具，用来下载文件、测试网络。诊断问题时常用。
#   unzip         —— 解压 zip 压缩包。
#   vim           —— 自带的文本编辑器，用来在服务器上改配置文件。
#   ca-certificates —— 网站安全证书的"总根目录"。
#                    没有它，服务器访问 https 网址时会报"证书不受信任"。
#   rsync         —— 高效的文件同步工具，只传输有变化的文件。
#   build-essential —— 编译工具包（C/C++ 编译器等）。
#                    很多软件安装时需要"现场编译"，这是基础条件。
#   ruby-full     —— Ruby 语言的完整环境。本站用的 Jekyll（网站生成程序）
#                    就是用 Ruby 写的，没有它没法构建网站。
#   zlib1g-dev / libffi-dev —— Ruby 安装某些组件时需要的辅助开发库，属于前置条件。
#   python3       —— Python 语言环境，用来运行抓取浏览量的那个脚本。
#   python3-pip   —— Python 的"软件安装器"，用于安装额外的 Python 工具包。
#   fail2ban      —— 【安全软件】自动封禁反复尝试登录的陌生 IP。
#                    能挡住大量"撞密码"式的恶意登录尝试，强烈建议保留。

ok "依赖安装完成"
echo "   Ruby 版本： $(ruby -v 2>/dev/null || echo '未安装')"
echo "   Nginx 版本： $(nginx -v 2>&1 || echo '未安装')"
# 打印两个关键软件的版本号，让您确认它们确实装好了。
# 里面的 2>/dev/null 意思是"报错信息不要显示"，|| 后面的意思是"万一取不到版本，
# 就打一句'未安装'"，这样输出更整洁，也不会因为取不到而报错中断。

# ------------------------------------------------------------
# ================== 第 3 步：准备文件和目录 ==================
log "3/7  关闭 Nginx 默认站点，创建网站目录"
rm -f /etc/nginx/sites-enabled/default
# 删掉 Nginx 自带的"默认欢迎页"配置。
# 【为什么要删？】不删的话，可能会和我们的网站配置同时生效、互相抢答，
# 导致访客有时看到我们的网站、有时看到 Nginx 的欢迎页。删掉最省心。
# rm -f 的 -f 是"文件不存在也不报错"，避免重复运行脚本时出错。

mkdir -p "$RELEASES_DIR" "$(dirname "$WEB_ROOT")" "$SRC_DIR"
# 一次性创建三个目录。
# mkdir -p 的 -p 意思是"需要的父目录也一并创建，已存在也不报错"。
# 三个目录的角色（本项目采用的发布方式，请重点理解）：
#   RELEASES_DIR —— 版本目录。每次发布都在这里建一个新文件夹存放本次网站文件。
#   WEB_ROOT 所在目录 —— 网站最终"对外呈现"的位置。
#   SRC_DIR      —— 源码目录。存放从 GitHub 拉下来的原始代码，是"原材料仓库"。
#   dirname "$WEB_ROOT" 表示"取 WEB_ROOT 的上一级目录"，
#   因为待会儿要对这个上级目录设置共享权限。

# 让 Nginx 用户与部署者都能读写发布目录（2775 = 组内共享 + 目录继承）
chown -R root:"$WEB_USER" "$(dirname "$WEB_ROOT")"
# 设置这个目录的所有者：
#   所有者（owner）设为 root，所属组设为 WEB_USER（网页服务器使用的账号）。
#   -R 表示"连同里面的所有子文件和子目录一起设置"。
# 【为什么这么设？】让"用管理员发布"和"网页服务器读取"两边的权限都能对上，
# 否则可能出现"文件传上去了，但网页服务器打不开"的诡异现象。

chmod 2775 "$(dirname "$WEB_ROOT")" "$RELEASES_DIR"
# 设置权限。2775 这四位数字的含义：
#   775 —— 所有者可读可写可进入，同组的人可读可进入，其他人可读可进入；
#   最前面那个 2 —— 【关键】"新建的文件自动继承上一级的组"。
#   为什么需要 2？这样以后每次发布自动建的新目录，也会自动带上正确的组，
#   省得每发布一次就要手动改权限。

ok "目录已就绪："
echo "   发布目录根： $(dirname "$WEB_ROOT")"
echo "   版本目录：   $RELEASES_DIR"
echo "   源码目录：   $SRC_DIR"
# 打印三个目录的实际路径，方便您核对和以后手工操作时使用。

# ------------------------------------------------------------
# ============= 第 4 步：写入 Nginx 站点配置 =============
log "4/7  写入 Nginx 站点配置 /etc/nginx/sites-available/${DOMAIN}.conf"
NGINX_TMPL='/etc/nginx/sites-available/__DOMAIN__.conf'
# 配置文件的路径。
# 注意文件名里带 __DOMAIN__，等会儿会被替换成真实域名。

# 【注意】下面 <<'NGINX_EOF' 这种写法叫"多行文本块"：
# 从这个标记开始，到后面的 NGINX_EOF 为止，中间的所有内容都会被原样写进上面那个文件。
# 单引号（'NGINX_EOF'）的作用是"内容原样照写，不做替换"，
# 这样才能在配置里保留占位符 __DOMAIN__，留到下一步再统一替换。
cat > "$NGINX_TMPL" <<'NGINX_EOF'
server {
    # server { } 是 Nginx 的一个"网站定义"块，一个块代表一个网站。
    listen 80;
    listen [::]:80;
    # 监听 80 端口，也就是 http 默认端口，让访客能通过普通网址访问。
    # [::]:80 是 IPv6 写法，一并监听，覆盖面更全。
    server_name __DOMAIN__ __WWW__;
    # 这个网站负责响应的域名，等会儿会替换成您的真实域名（含带 www 的版本）。

    root __WEB_ROOT__;
    # 网站文件放在哪个目录（"根目录"），等会儿替换成真实路径。
    index index.html;
    # 访客只访问目录（没指名具体文件）时，默认递上 index.html 给他。

    # ① 静态资源长缓存（图片/CSS/JS 30 天）
    location ~* \.(?:css|js|jpg|jpeg|png|gif|webp|svg|ico|woff2?|ttf|eot)$ {
        # 这是一条"规则匹配"：凡是请求的是这些类型的文件，就按下面的方式处理。
        # 【为什么要单独处理？】因为图片、字体、样式表这类文件基本不会变，
        # 让访客的浏览器"记牢 30 天"，第二次访问时直接从本地取，
        # 不用重新下载，网站打开会明显更快。
        expires 30d;
        add_header Cache-Control "public, max-age=2592000";
        # 两条都是"告诉浏览器可以缓存 30 天"的标准写法（2592000 = 30 天的秒数）。
        access_log off;
        # 这些文件访问太频繁，不记录日志，避免日志文件被撑爆。
        # 【可DIY修改】想让缓存更久可把 30d 改成 365d；
        # 但如果经常换图片，缓存太久会导致访客"看到的是旧图"。
    }

    # ② HTML 不缓存，保证「更新后刷新就能看到」
    location ~* \.html$ {
        add_header Cache-Control "no-cache, must-revalidate";
        # 网页文件（HTML）要求每次都向服务器确认一下有没有更新。
        # 【为什么和上面相反？】因为网页内容是会变的（比如浏览量数字）。
        # 如果不缓存，您刚发完文章刷新就能看到最新版，体验最符合直觉。
    }

    # ③ gzip 压缩（Chirpy 的 CSS/JS 较大，强烈建议开启）
    gzip on;
    # 开启压缩：服务器把网页内容压缩后再发出去，访客下载的数据更少、打开更快。
    # 可以理解为"发快递前先把衣服抽真空，体积小了运费也省了"。
    gzip_vary on;
    # 让中间的网络缓存知道"压缩版和未压缩版是不同的东西"，避免发错版本。
    gzip_min_length 1024;
    # 小于 1024 字节（1KB）的内容不压缩。
    # 因为小文件压缩后可能反而更大、还多耗 CPU，不划算。
    gzip_proxied any;
    # 即使请求经过了中间代理，也照样压缩。
    gzip_types text/plain text/css text/xml application/javascript application/json application/xml image/svg+xml;
    # 指定对哪些类型的文件做压缩（文本类才有效，图片本身就是压缩格式，压不了）。
    # 【可DIY修改】一般不用改。改错可能导致某些文件不压缩，只是速度慢一点，不会出错。

    # ④ 404 页面（Chirpy 会生成 404.html）
    error_page 404 /404.html;
    # 访客访问了不存在的地址时，显示我们自己做的 404 页面，
    # 而不是 Nginx 那句生硬的英文提示，观感更专业。
    location = /404.html { internal; }
    # internal 表示这个页面只能被服务器内部调用，
    # 不让访客直接输入 /404.html 来访问（保持它只作为错误提示页存在）。

    # ⑤ 保护隐藏文件（.git 等），但放行 .well-known（证书校验要用）
    location ~ /\.(?!well-known) { deny all; }
    # 【安全设置，很重要】拒绝外部访问所有以点开头的隐藏文件。
    # 为什么？因为 .git 这类文件里可能包含源码历史等敏感信息，
    # 一旦被下载走，别人就能看到很多不该看的东西。
    # 但 .well-known 要放行——那是申请 HTTPS 证书时用来做域名验证的目录，
    # 拦掉它证书就签不下来了。

    # ⑥ 目录式链接：/posts/xxx/ 自动找 index.html
    try_files $uri $uri/ =404;
    # 处理访客请求的规则，按顺序尝试：
    #   ① $uri     —— 先看有没有这个同名文件，有就直接给他；
    #   ② $uri/    —— 再看有没有这个同名目录，有就进目录里找默认的 index.html；
    #   ③ =404     —— 都没有，就返回 404（找不到）。
    # 因为本站文章网址是 /posts/xxx/ 这种"目录式"的，
    # 靠这条规则才能自动找到里面的 index.html。
}
NGINX_EOF

# 把占位符替换成真实值
sed -i "s|__DOMAIN__|${DOMAIN}|g; s|__WWW__|${WWW_DOMAIN}|g; s|__WEB_ROOT__|${WEB_ROOT}|g" "$NGINX_TMPL"
# 把配置文件里的三个占位符，换成配置文件中填的真实值。
# sed -i = 直接在原文件上修改。
# s|A|B|g = 把所有的 A 替换成 B（s 是替换、g 是"全部出现的地方都换"）。
# 这里用 | 当分隔符而不是常用的 /，是因为要替换的内容里包含斜杠，
# 用 | 就不用一个个转义，写起来更清爽。
# 三个占位符分别换成：域名、带 www 的域名、网站文件目录。

ln -sfn "$NGINX_TMPL" "/etc/nginx/sites-enabled/${DOMAIN}.conf"
# 在"已启用"目录里放一个链接，指向刚才写的配置文件。
# 【为什么要有这一步？】Nginx 只认 sites-enabled 目录里的配置，
# 而实际内容放在 sites-available 目录。这样做的好处：
# 想让网站下线，只要删掉这个链接就行，配置文件本身还在，随时能恢复。
# 各参数含义：-s 创建链接、-f 已存在就覆盖、-n 把链接当成普通文件处理（不影响已存在的内容）。

# ------------------------------------------------------------
# ================ 第 5 步：检查并启动 Nginx ================
log "5/7  校验并启动 Nginx"
nginx -t
# 让 Nginx 检查一下配置写得对不对。
# 【这一步很关键】如果配置有语法错误，直接重启会导致网站全部打不开。
# 先检查一遍，有问题会在这一步就报出来，就能及时修改。
# 看到 "syntax is ok" 和 "test is successful" 就说明没问题。
systemctl enable nginx
# 设置"服务器开机时自动启动 Nginx"。
# 作用：万一服务器意外重启（比如断电、维护），网站能自己恢复，不用您手工去启动。
systemctl restart nginx
# 重新启动 Nginx，让新配置生效。
systemctl is-active --quiet nginx && ok "Nginx 已运行"
# 检查 Nginx 现在是不是正在运行，是的话打印一句绿色的成功提示。
# --quiet 表示"别输出一堆内容，只告诉我成功还是失败"，输出更干净。

# ------------------------------------------------------------
# ============== 第 6 步：开启安全防护（fail2ban） ==============
log "6/7  开启 fail2ban（防 SSH 暴力破解）"
systemctl enable fail2ban >/dev/null 2>&1 || true
systemctl restart fail2ban >/dev/null 2>&1 || true
ok "fail2ban 已启动"
# fail2ban 的作用：监视登录尝试，发现某个 IP 连续输错密码，
# 就自动把它拉黑一段时间。
# 【为什么需要？】服务器一旦连上公网，每天会有大量陌生程序不停尝试
# 用常见用户名和密码登录（俗称"撞库"或"暴力破解"），
# 不开这个防护，很容易被撞开一个弱密码。
# >/dev/null 2>&1 的意思是"这次操作的输出（不管是正常消息还是报错）都不要显示"。
# 后面跟 || true 表示"就算执行失败也别让脚本中断"。
# 【为什么允许失败？】因为某些服务器环境可能不支持 fail2ban，
# 它只是额外防护，装不上也不该影响网站运行，所以不强求。

