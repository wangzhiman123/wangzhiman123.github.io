#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  publish.sh —— 核心发布脚本（构建 → 自检 → 原子切换 → 清理旧版本）
#
#  一句话概括：这是整个部署体系里最重要的一个脚本，
#  以后每次想更新网站，最终都是它在干活。
#  它把"把新版本网站安全地换上线上"这件复杂的事做得很稳。
#
#  特点：
#    · 「原子切换」：先构建到新版本目录，构建成功才把软链指过去，
#      所以构建期间线上仍是旧版本，不会出现"传一半的网站"。
#    · 「秒级回滚」：旧版本目录都留着，改软链即可回退。
#
#  【先说清楚两个关键概念，后面全靠它们】
#
#  概念一：软链（符号链接）
#    可以理解为"快捷方式"。想象您有一个文件夹叫"当前网站"，
#    它其实只是一个指针，指向"第三版"那个真正的文件夹。
#    想让网站换成"第四版"？只要把指针改成指向第四版就行了——
#    一瞬间完成，而且不需要搬动任何文件。
#    这正是"原子切换"能瞬间完成、且不会出错的原理。
#
#  概念二：原子切换（先建新的，再切指针）
#    如果反过来做（先删旧的再传新的），那么在这几分钟里网站是坏的，
#    访客会看到报错。而本脚本的做法是：
#      新版本在一个全新目录里慢慢构建（此时线上完全不受影响）
#      → 构建成功、自检通过
#      → 才把指针一改（这一步是瞬间的）
#      → 于是"旧的完好"直接变成"新的完好"，中间没有任何空档。
#    "原子"这个词就是这个意思：要么完全没变，要么完全变好，不存在中间状态。
#
#  用法（服务器上）：
#      bash publish.sh
#      bash publish.sh --from-git     # 先 git pull 再发布
# ============================================================
set -euo pipefail
# 脚本安全模式（出错就停、变量必须已定义、管道任一环节出错即失败）。
# 对发布脚本来说这一行尤其重要：任何一步出问题都应该立刻停，
# 绝不能在构建失败的情况下还把网站切换过去。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 取得本脚本所在文件夹的绝对路径。

CONF="$HERE/config.env"
[[ -f "$CONF" ]] || { echo "❌ 找不到 $CONF，请先 cp config.env.example config.env 并填写"; exit 1; }
# 检查配置文件是否存在，不存在就提示退出。
source "$CONF"
# 读取配置内容（DOMAIN、SRC_DIR、RELEASES_DIR、WEB_ROOT、KEEP_RELEASES 等）。

log() { echo -e "\n\033[1;34m▶ $*\033[0m"; }
# 打印蓝色步骤标题的小工具。
ok()  { echo -e "\033[1;32m✅ $*\033[0m"; }
# 打印绿色成功提示的小工具。

FROM_GIT=0
[[ "${1:-}" == "--from-git" ]] && FROM_GIT=1
# 判断运行时有没有带 --from-git 这个参数。
# 拆开读：
#   FROM_GIT=0 先默认"不需要从 Git 拉取"；
#   "${1:-}" 取第一个参数（没传参数就是空字符串，:- 是为了防止报错）；
#   如果它等于 --from-git，就把 FROM_GIT 设成 1（表示"需要"）。
# 这个开关的用处：定时任务希望"总是拉取最新的再发布"，就带上这个参数；
# 而手工发布时往往用服务器上现有的代码，就不带。

STAMP="$(date +%Y%m%d-%H%M%S)"
# 生成一个时间戳，格式如 20261013-093045（年月日-时分秒）。
# 用来给每个版本目录起一个不重复的名字。
REL="$RELEASES_DIR/$STAMP"
# 拼出本次新版本目录的完整路径。
# 每次发布都是全新目录，所以旧版本天然被保留下来，随时能回退。

cd "$SRC_DIR"
# 进入源码目录，后面的构建命令都在这里执行。
ok "源码目录：$(pwd)"
# 打印当前所处目录，让您确认没跑错地方（pwd = 显示当前目录）。
# 【为什么值得打印？】"在错误的目录里构建"是常见失误，
# 提前把路径显示出来，看一眼就能发现问题。

# ------------------------------------------------------------
# ============ 第 0 步：从 GitHub 同步最新代码（可选） ============
if [[ $FROM_GIT -eq 1 ]]; then
  log "0/5  从 Git 拉取最新代码"
  if [[ -d .git ]]; then
    # 确认当前目录确实是个 Git 仓库。
    git fetch --all --prune
    # 从 GitHub 拉回最新的版本信息。
    git reset --hard "origin/${REPO_BRANCH}"
    # 把本地文件强制恢复成远程仓库最新版。
    # 效果上等于"把服务器上的源码同步成 GitHub 上的样子"。
    ok "已同步到 origin/${REPO_BRANCH}"
  else
    echo "⚠️  当前目录不是 git 仓库，跳过 git pull（将直接用现有文件构建）"
    # 不是 Git 仓库（比如您是用本地上传的方式传上来的源码），
    # 那就跳过同步这一步，直接用现有文件构建。
    # 这样两种源码来源都能工作，脚本更宽容好用。
  fi
fi

# ------------------------------------------------------------
# ==================== 第 1 步：检查环境 ====================
log "1/5  检查构建环境"
command -v bundle >/dev/null 2>&1 || { echo "❌ 没装 bundler，请先：gem install bundler"; exit 1; }
# 检查系统里有没有 bundler 这个工具。
# bundler 是 Ruby 的"组件管理器"，负责按清单安装项目需要的组件。
#   command -v xxx = 问系统"xxx 这个命令在哪"，能找到就说明装了；
#   >/dev/null 2>&1 = 把输出丢掉，我们只关心成功失败；
#   || { ... } = 找不到就打印提示并退出。
# 提示里的 gem install bundler 是解决办法——安装这个工具的命令。
[[ -f Gemfile ]] || { echo "❌ $SRC_DIR 下没有 Gemfile，源码放错位置了？"; exit 1; }
# 检查项目清单文件在不在，不在说明源码位置不对。

# ------------------------------------------------------------
# ============== 第 2 步：安装/校验所需组件 ==============
log "2/5  安装/校验依赖（首次会慢，之后很快）"
if [[ ! -f Gemfile.lock ]]; then
  # Gemfile.lock 是"版本锁定清单"：它把每个组件的确切版本号记下来。
  # 【为什么需要锁定版本？】如果不锁，今天装的是 A 版本、半年后装的是 B 版本，
  # 可能出现"以前能正常构建，现在突然报错"这种莫名其妙的问题。
  # 锁住版本，就能保证任何时候构建结果都一致、可复现。
  echo "   未发现 Gemfile.lock，正在生成（用于锁定依赖版本）…"
  bundle install
  # 按清单安装所需组件，同时生成锁定文件。
  git add Gemfile.lock 2>/dev/null || true
  # 把新生成的锁定文件加到"待提交"名单，方便下次同步时一起带过去。
  # 后面两个 2>/dev/null || true 表示"失败也不报错中断"——
  # 因为在非 Git 仓库里这些命令本来就会失败，但完全不影响发布。
  git commit -m "chore: 锁定依赖版本 (Gemfile.lock)" 2>/dev/null || true
else
  bundle install --quiet
  # 已经有锁定文件了，就按它安装/核对组件。
  # --quiet 表示"少说废话"（只报错、不打印一大堆安装进度），输出更清爽。
fi

# ------------------------------------------------------------
# ================= 第 3 步：构建网站（生成网页） =================
log "3/5  构建站点 → $REL"
mkdir -p "$REL"
# 创建新版本目录。
JEKYLL_ENV=production bundle exec jekyll build -d "$REL"
# 【核心命令】真正把文章编译成网页。
# 拆开读：
#   JEKYLL_ENV=production = 声明这是正式环境（会启用压缩等优化）；
#   bundle exec           = 用本项目锁定的组件版本来执行，避免版本混乱；
#   jekyll build          = 让 Jekyll 开始构建网站；
#   -d "$REL"             = 把生成结果放到新版本目录里。
# 【注意】构建过程可能持续几十秒到几分钟，但此时线上网站完全不受影响，
# 访客仍正常访问旧版本——这正是先建后切的价值。

[[ -f "$REL/index.html" ]] || { echo "❌ 构建产物里没有 index.html，构建可能失败"; exit 1; }
# 【重要检查】看看新版本里有没有首页文件。
# 如果没有，说明构建其实失败了（但命令却"成功返回"了，这种情况偶尔会发生）。
# 在这里拦住，就不会把一个空壳网站切换上线。
ok "构建完成，文件数：$(find "$REL" -type f | wc -l)"
# 统计并打印生成的文件数量，让您对结果有个直观感受。
# find ... -type f 是"找出所有普通文件"，wc -l 是"数一数有多少行"（也就是多少个文件）。

# ------------------------------------------------------------
# ============= 第 4 步：构建后自检（挑毛病） =============
log "4/5  构建后自检（html-proofer）"
bundle exec htmlproofer "$REL" \
  --disable-external \
  --ignore-urls "/^http:\/\/127.0.0.1/,/^http:\/\/0.0.0.0/,/^http:\/\/localhost/,/^http:\/\/lsrz\.cs\.mfa\.gov\.cn/"
# 用 htmlproofer 检查新版本里的链接是否正常。两个参数：
#   --disable-external = 只查站内链接，不查外站链接。
#       原因：外站偶尔访问不了很正常，不该因为别人家的网站打不开，
#             就说我们自己的发布失败。同时也能加快检查速度。
#   --ignore-urls      = 忽略这几个"本机调试地址"，
#       它们在正式网站上本不该出现，检查出来也没意义。
# 【注意】与 GitHub Actions 里不同，这里没有 continue-on-error，
# 也就是说自检不通过就会中断发布、网站继续用旧版本。
# 这是刻意的：手动发布时从严把关更稳妥，宁可不上线也不上线一个坏版本。
ok "自检通过"

# ------------------------------------------------------------
# ================= 第 5 步：切换发布目录（关键一步） =================
log "5/5  原子切换发布目录"
if [[ -L "$WEB_ROOT" ]]; then
  # 情况一：WEB_ROOT 已经是个软链（说明以前就是用本脚本发布的）。
  # -L 表示"这是个符号链接（快捷方式）"。
  ln -sfn "$REL" "$WEB_ROOT"
  # 【最关键的一行】把快捷方式重新指向新版本目录。
  # 这一下就是所谓的"原子切换"：瞬间生效，中间没有空档。
  # 各参数含义：-s 创建软链、-f 已存在就替换、-n 当成普通文件处理。
elif [[ -e "$WEB_ROOT" ]]; then
  # 情况二：WEB_ROOT 是个真实目录（第一次用本脚本时可能是这种状态，
  # 比如之前是手工把文件直接放在那里的）。
  # 首次：旧的可能是个真实目录，先改名备份再改成软链
  BK="${WEB_ROOT}.bak.$(date +%s)"
  mv "$WEB_ROOT" "$BK"
  # 先把原来的真实目录改名保留（不删！），万一新版本有问题还能立刻换回来。
  # 名字后面缀了个时间戳（date +%s 是当前时间换算成的秒数），保证不重名。
  ln -sfn "$REL" "$WEB_ROOT"
  # 然后再建立指向新版本的软链。
  echo "   原目录已备份为：$BK"
  # 告诉您备份在哪，将来若要回退可以去那里找。
else
  # 情况三：WEB_ROOT 还不存在，直接建立软链即可。
  ln -sfn "$REL" "$WEB_ROOT"
fi

ok "已发布，$WEB_ROOT → $REL"
# 打印"谁指向谁"，方便确认切换成功。
# 现在网站已经更新完成，访客刷新就能看到最新内容。

# 清理旧版本，只保留最近 KEEP_RELEASES 个
if [[ -n "${KEEP_RELEASES:-}" ]] && [[ "$KEEP_RELEASES" =~ ^[0-9]+$ ]]; then
  # 先确认这个设置项有值（-n 表示"非空"），而且确实是个纯数字
  # （=~ ^[0-9]+$ 是"从头到尾都是数字"的检查）。
  # 【为什么要验数字？】因为接下来的命令会按这个数字删除文件，
  # 万一里面写的是奇怪内容，可能误删东西。先验一遍更安全。
  ls -1dt "$RELEASES_DIR"/*/ 2>/dev/null | tail -n "+$((KEEP_RELEASES + 1))" | xargs -r rm -rf
  # 【这一步逐段读，它稍复杂但很巧妙】
  #   ls -1dt "$RELEASES_DIR"/*/  = 列出所有版本目录，
  #        -1 每行一个、-d 只列目录本身、-t 按修改时间从新到旧排序。
  #   | tail -n "+N"              = 从第 N 行开始，取后面的所有行
  #        （N = 保留数量 + 1）。也就是"跳过最新 N 个，只剩下要删的旧版本"。
  #   | xargs -r rm -rf           = 把这些路径交给删除命令，逐个删掉。
  #        -r 表示"如果前面没有输出，就不要执行删除"（重要防护！否则可能误删）。
  #   【设计意图】只保留最近几次发布，避免版本目录越堆越多、把服务器磁盘占满；
  #   同时又留够几个，方便出问题时回退。
  #   【可DIY修改】保留几个由 config.env 里的 KEEP_RELEASES 控制。
  echo "   当前保留版本："
  ls -1dt "$RELEASES_DIR"/*/ 2>/dev/null | head -n "$KEEP_RELEASES" | sed 's/^/     /'
  # 打印出目前留着的那几个版本目录，前面统一加几个空格让排版更整齐。
  # head -n N 表示"只取最前面 N 行"。
fi

echo
ok "发布完成 🎉  打开 https://${DOMAIN}/ 查看"
# 打印成功信息，并给出网址提示，方便您直接打开验收。
echo "   回滚命令： ln -sfn $RELEASES_DIR/<上一个版本> $WEB_ROOT"
# 【很实用的一行】告诉您万一新版本有问题怎么"一键回到上一版"。
# 具体做法：把上面命令里的 <上一个版本> 换成具体的版本目录名（就用刚才打印出来的那些），
# 然后执行即可——网站瞬间回到那个版本。
# 这正是前面"每个版本都留一个独立目录"的价值所在：回退就是改一下快捷方式，几秒钟的事。
