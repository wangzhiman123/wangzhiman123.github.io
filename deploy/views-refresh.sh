#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  views-refresh.sh —— 抓取最新浏览量 → 重新构建发布
#
#  一句话概括：这是"更新浏览量"的最终执行者。
#  它做三件事：去统计服务问最新数字 → 把数据存好 → 重新构建网站让新数字上线。
#
#  为什么这三件事必须串在一起做？回顾一下浏览量显示的原理：
#   浏览量数字是"编译时印死在网页里"的。所以光更新数据文件没用，
#   必须再重新构建一次，网页上的数字才会变。本脚本就是把这一串动作打包好。
#
#  这个脚本替代原来 GitHub Actions 里的 update-views.yml：
#    · 运行 scripts/update_views.py，把真实浏览量写入 _data/views.json
#    · 若为 git 仓库，顺手提交这两个数据文件（避免下次 git pull 冲突）
#    · 然后重新构建发布，让页面上的浏览量更新
#
#  一般不用手动跑，由 04-install-views-cron.sh 装成定时任务。
#  但偶尔想"立刻更新一下"，也可以手工执行：bash views-refresh.sh
# ============================================================
set -euo pipefail
# 脚本安全模式（出错就停、变量必须已定义、管道任一环节出错即失败）。
# 对定时任务尤其重要：这样出错会立刻中断并在日志里留下线索，而不是默默跑歪。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 取得本脚本所在文件夹绝对路径。
CONF="$HERE/config.env"
[[ -f "$CONF" ]] || { echo "❌ 找不到 $CONF"; exit 1; }
# 检查配置文件存在。
source "$CONF"
# 读取配置（DOMAIN、SRC_DIR 等）。

cd "$SRC_DIR"
# 进入源码目录——因为下面的抓取脚本和构建都必须在这个目录里执行。

echo "[$(date '+%F %T')] 开始刷新浏览量"
# 打印一行带时间的开始提示。
# 格式：$(date '+%F %T') 会输出类似 2026-10-13 03:00:01 这样的时间。
# 【为什么要带时间？】因为这个脚本通常在半夜定时运行，您看不到它跑；
# 有了时间戳，事后翻日志就能知道每次是什么时候执行的、间隔是否正常。
SITE_URL="https://${DOMAIN}" python3 scripts/update_views.py
# 【关键一步】执行抓取脚本，把最新浏览量写进数据文件。
# 拆开读：
#   SITE_URL="https://..." —— 在命令前面临时设置一个环境变量，
#       告诉抓取脚本"网站地址是什么"。放在行首的写法表示
#       "只对这一条命令生效"，不会影响后面别的命令。
#   python3 scripts/update_views.py —— 运行抓取脚本本身。
# 这个脚本内部的工作（去问统计服务、做轮询补偿纠正等），
# 详见 scripts/update_views.py 里的详细注释。

# git 仓库则提交数据变更，避免和后续 git pull 打架
if [[ -d .git ]]; then
  # 只在当前目录是 Git 仓库时才做提交。
  # 如果您是用本地上传的方式部署的（没有 .git 目录），就跳过这一步，不影响使用。
  git add _data/views.json _data/pv_state.json 2>/dev/null || true
  # 把两个更新后的数据文件加入"待提交"名单。
  git -c user.name="cron" -c user.email="cron@localhost" \
      commit -m "chore(data): update post views" >/dev/null 2>&1 \
    && echo "   数据已提交" || echo "   数据无变化，跳过提交"
  # 【这一段比较绕，但很重要，值得看明白】
  #   git -c user.name="cron" -c user.email="cron@localhost"
  #       临时给这次提交指定一个名字和邮箱。
  #       为什么要指定？因为定时任务是无人值守运行的，
  #       服务器上可能根本没配置过 Git 的用户信息，
  #       不指定的话提交会直接失败并报"请先设置用户名"。
  #   >/dev/null 2>&1  把提交过程的输出都丢掉，只保留我们自己的提示，日志更干净。
  #   末尾的 && ... || ...  是一套"成则报喜、败则报安"的写法：
  #       提交成功 → 打印"数据已提交"；
  #       提交失败 → 打印"数据无变化，跳过提交"。
  #       【为什么失败也当正常？】因为绝大多数情况下"失败"其实是好事——
  #       浏览量完全没变，没有要提交的内容，Git 会说"没什么可提交的"。
  #       这时不该当成错误处理，否则每天都会出现一条虚假的报错记录，
  #       反而会掩盖真正的故障。
  #   【这一步的真正目的】把数据文件在服务器本地提交掉，
  #   这样下次执行 git pull 时不会因为"本地有未提交的改动"而冲突报错。
fi

echo "   正在重新构建发布…"
# 打印进度提示，因为构建要花几十秒到几分钟，让人知道还没卡死。
bash "$HERE/publish.sh"
# 【关键衔接】调用发布脚本，重新构建网站并把新版本切换上线。
# 这一步执行完，网页上的浏览量数字就是最新的了。
# 构建过程的详细逻辑（原子切换、自检、清理旧版本等）见 deploy/publish.sh。
echo "[$(date '+%F %T')] 完成"
# 打印带时间的结束提示。
# 【小技巧】对比开头的开始时间和这里的结束时间，就能看出这次刷新总共花了多久。
# 如果某天发现耗时突然变长很多，往往说明网络或服务器状态有变化，值得留意。
