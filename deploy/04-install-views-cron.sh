#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  04-install-views-cron.sh —— 安装「浏览量定时刷新」任务
#
#  一句话概括：这个脚本给服务器装一个"闹钟"，
#  让它每隔几小时自动更新一次各文章的浏览量数字。
#
#  【先说清楚 cron 是什么】
#  cron 是 Linux 自带的"定时任务"功能，相当于手机里的闹钟+日程提醒组合：
#  您可以告诉它"每天凌晨 3 点执行这个脚本"，它就会准时照做。
#  设置好的这些定时安排集中保存在一个叫 crontab 的清单里，
#  用 crontab -l 命令就能查看当前有哪些任务（-l = list，列出）。
#
#  替代原 GitHub Actions 的 update-views.yml：
#  按 config.env 里的 VIEWS_CRON 定时执行 views-refresh.sh。
#  —— 也就是说，本项目的浏览量刷新有"两套方案"：
#     方案一：用 GitHub 的免费云机器人跑（见 .github/workflows/update-views.yml）；
#     方案二：用自己服务器上的定时任务跑（就是这个脚本装的）。
#     两套只需选一套，用了这个就可以把 GitHub 那套关掉，反之亦然。
#     自己服务器跑的好处：时间点完全可控，不受 GitHub 高峰期延迟影响。
#
#  用法（服务器上，root）：
#      bash 04-install-views-cron.sh          # 安装/更新
#      bash 04-install-views-cron.sh --remove # 卸载
# ============================================================
set -euo pipefail
# 脚本安全模式（出错就停、变量必须已定义、管道任一环节出错即失败）。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 取得本脚本所在文件夹绝对路径。
CONF="$HERE/config.env"
[[ -f "$CONF" ]] || { echo "❌ 找不到 $CONF"; exit 1; }
# 检查配置文件存在。
source "$CONF"
# 读取配置（关键是 VIEWS_CRON —— 定时刷新的时间安排）。

ok()  { echo -e "\033[1;32m✅ $*\033[0m"; }
# 打印绿色成功提示的小工具。
# （本脚本不需要打印步骤标题，所以没定义 log。）

chmod +x "$HERE/views-refresh.sh" "$HERE/publish.sh" 2>/dev/null || true
# 给两个脚本加上"可执行"权限。
# 【为什么需要？】从 Windows 传上来的文件往往丢失了执行权限，
# 定时任务执行时会报"权限不足"而静默失败——这是很常见又很难查的坑，
# 所以这里主动补一下。后面的 2>/dev/null || true 表示"失败也不中断"。

CRON_LINE="${VIEWS_CRON} /bin/bash $HERE/views-refresh.sh >> /var/log/site-views.log 2>&1"
# 拼出要在 crontab 里写入的那一整行内容。逐段读：
#   ${VIEWS_CRON}              —— 时间安排，来自 config.env，例如 "0 3,9,15,21 * * *"；
#                                五个位置的含义依次是：分 时 日 月 星期。
#                                上面那串的意思就是"每天 3 点、9 点、15 点、21 点各跑一次"。
#   /bin/bash .../views-refresh.sh —— 到点要执行的具体脚本。
#   >> /var/log/site-views.log —— 把执行过程的输出追加保存到日志文件。
#                                >> 表示"在文件末尾接着写"（不覆盖历史记录）。
#                                有了日志，万一哪天数字没更新，可以来这里查原因。
#   2>&1                       —— 把错误信息也一起写进同一个日志文件。
#                                （否则错误信息会跑别处去，查问题时容易漏掉。）

MARKER="# 王志满律师网-浏览量刷新"
# 给这一行加一个"标记备注"。
# 【为什么要标记？】因为 crontab 里可能有您自己或其他软件设置的任务，
# 我们只应该动自己这一条，绝不能误删别人的。
# 靠这个独特的标记，脚本就能准确认出"哪一行是我自己写的"。
# 【可DIY修改】这个备注文字可以改，但如果改了，
# 请务必同时改掉下面 --remove 部分里对应的内容，否则卸载会失效。

if [[ "${1:-}" == "--remove" ]]; then
  # 【卸载分支】运行时带了 --remove 参数，就走这里，把定时任务删掉。
  crontab -l 2>/dev/null | grep -v "$MARKER" | grep -v "views-refresh.sh" | crontab - || true
  # 逐段读这个"管道组合"：
  #   crontab -l           读出当前的定时任务清单；
  #   | grep -v "$MARKER"  过滤掉带标记的那一行（-v 表示"反向筛选"，即"保留不匹配的"）；
  #   | grep -v "views-refresh.sh"  再把提到本刷新脚本的行也过滤掉，
  #       双重保险，防止早期版本没写标记的遗留条目留下来。
  #   | crontab -          把过滤后的结果写回去，成为新的清单。
  #   最终效果：除了我们这一条，其他任务原封不动。
  ok "已卸载浏览量定时任务"
  crontab -l 2>/dev/null | sed 's/^/   /' || true
  # 打印卸载后剩下的定时任务，前面加 3 个空格让排版整齐，方便您确认结果。
  exit 0
  # 干完活直接结束，不再往下走安装流程。
fi

touch /var/log/site-views.log
# 先创建日志文件（如果已经存在就只更新一下时间，不会清空内容）。
# 【为什么要先建？】有些系统的安全设置会限制"只能往已存在的文件里写"，
# 提前建好能避免定时任务因为"没权限创建新文件"而失败。

# 先删旧的同类条目，再写入新条目（实现幂等）
TMP="$(mktemp)"
# 建一个临时文件用来中转内容。
# mktemp 会自动生成一个不重名的文件名，避免和别人撞车。
crontab -l 2>/dev/null | grep -v "$MARKER" | grep -v "views-refresh.sh" > "$TMP" || true
# 【先删旧的】读出当前清单，去掉我们自己以前写的那一行，其余内容存进临时文件。
# 这一步实现了"幂等"——也就是"这个脚本可以反复运行，结果始终一致"。
# 【为什么需要反复运行？】因为您可能会改 VIEWS_CRON 的时间（比如从每天 1 次改成 4 次），
# 然后重新跑一次本脚本。如果不先删旧的，就会变成"新旧两条都在"，
# 结果新旧时间点都触发，白白多跑几遍。
{
  echo "$MARKER"
  echo "$CRON_LINE"
} >> "$TMP"
# 把标记行和时间安排行追加到临时文件末尾。
# 大括号 { } 是"把多条命令的输出打包成一组"，一起写进文件。
crontab "$TMP"
# 把整理好的内容一次性写回系统，成为新的定时任务清单。
rm -f "$TMP"
# 删掉临时文件中转站，保持环境干净。

ok "已安装定时任务："
echo "   $CRON_LINE"
# 把刚装好的这条任务内容显示出来，让您心里有数。
echo
echo "   当前 crontab："
crontab -l 2>/dev/null | sed 's/^/     /'
# 把现在系统里全部的定时任务都列出来（每行前面加 5 个空格缩进），
# 这样您能确认：既装上了我们的任务，又没弄丢别的任务。
echo
echo "   日志文件： /var/log/site-views.log"
# 告诉您日志在哪——将来若发现浏览量没更新，第一时间来看这个文件。
echo "   想立刻验证一次：  bash $HERE/views-refresh.sh"
# 给出一个很实用的建议命令：不用干等定时时间到，
# 直接手工跑一次刷新脚本，就能立刻验证这套流程通不通。
# 建议第一次装好后真的跑一下试试。
