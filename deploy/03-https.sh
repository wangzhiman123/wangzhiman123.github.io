#!/usr/bin/env bash
# ============================================================
# 【本文件是什么？】
#  03-https.sh —— 申请并配置 HTTPS 证书（Let's Encrypt，免费 + 自动续期）
#
#  一句话概括：这个脚本给网站装上"加密锁"，
#  让访客通过 https:// 安全地访问（浏览器地址栏出现小锁图标），
#  并且设置成"到期自动续期"，以后不用管。
#
#  【什么是 HTTPS？为什么必须要？】
#  普通访问（http）相当于用明信片寄信——路上谁都能看内容。
#  HTTPS 相当于把内容装进带锁的信封——中间人看不到、也改不了。
#  现在浏览器对 http 网站会明确提示"不安全"，访客会不放心；
#  搜索引擎也会降低 http 网站的排名。所以正式网站必须上 HTTPS。
#
#  【证书是哪里来的？要花钱吗？】
#  用 Let's Encrypt 这个国际公益机构签发的免费证书，效果和付费证书一样被浏览器信任。
#  唯一的"代价"：证书有效期只有 90 天，必须定期续期——
#  所以下面第 3 步特别重要，它把"自动续期"配置好，免得您 90 天后再忙一次。
#
#  前置条件：
#    · 域名的 A 记录已经指向这台服务器
#      什么叫 A 记录？就是"域名 → 服务器 IP"的对照表，
#      告诉互联网"访问 2019527.xyz 时该去找哪台机器"。
#      在哪设置：您买域名的地方（域名注册商）的"域名解析/DNS"页面里加一条 A 记录。
#    · 80 端口能从公网访问（备案接入已通过）
#      因为验证证书时，Let's Encrypt 会来访问您的网站确认域名真的是您的。
#
#  用法（服务器上，root）：
#      bash 03-https.sh
# ============================================================
set -euo pipefail
# 脚本安全模式（出错就停、变量必须已定义、管道任一环节出错即失败）。

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# 取得本脚本所在文件夹绝对路径。
CONF="$HERE/config.env"
[[ -f "$CONF" ]] || { echo "❌ 找不到 $CONF"; exit 1; }
# 检查配置文件存在。
source "$CONF"
# 读取配置（DOMAIN、WWW_DOMAIN、LE_EMAIL）。

log() { echo -e "\n\033[1;34m▶ $*\033[0m"; }
ok()  { echo -e "\033[1;32m✅ $*\033[0m"; }

[[ "${EUID:-$(id -u)}" -eq 0 ]] || { echo "❌ 请用 root 运行： sudo bash $0"; exit 1; }
# 确认是管理员身份在运行（安装软件、改网站配置都需要管理员权限）。
# 不是的话提示用 sudo 运行。

# ------------------------------------------------------------
log "1/4  安装 certbot"
export DEBIAN_FRONTEND=noninteractive
# 关掉安装过程中的交互提问，让脚本能一路自动跑完。
apt-get install -y certbot python3-certbot-nginx
# 安装证书工具，两个组件各有分工：
#   certbot              —— 负责"向 Let's Encrypt 申请证书"以及"到期续期"。
#   python3-certbot-nginx —— 是它跟 Nginx 之间的桥梁，
#                            能让证书申请完成后自动把 Nginx 配置改好，省去手工步骤。

# 组装域名参数（www 为空就不加）
DOMAIN_ARGS=(-d "$DOMAIN")
# 准备一个参数清单，先放入主域名。
# -d 是 certbot 用来指定"要给哪些域名签证书"的记号，相当于"domain"的缩写。
if [[ -n "${WWW_DOMAIN:-}" ]]; then
  DOMAIN_ARGS+=(-d "$WWW_DOMAIN")
fi
# 如果配置里填了带 www 的域名，就再追加一个 -d 参数。
# 这样一张证书能同时覆盖"不带 www"和"带 www"两个地址，
# 访客用哪种写法访问都能正常打开，不会报证书错误。
# 【说明】+= 的意思是"往清单后面追加一项"。

# ------------------------------------------------------------
log "2/4  申请证书并自动配置 HTTPS（含 http→https 跳转）"
certbot --nginx \
  "${DOMAIN_ARGS[@]}" \
  --email "$LE_EMAIL" \
  --agree-tos --no-eff-email \
  --redirect \
  --non-interactive
# 【核心命令】逐项解释参数：
#   --nginx              表示"通过 Nginx 来配置"。certbot 会自己读取 Nginx 配置、
#                        完成域名验证，事后再把证书配置写进去，全程不需要您手工改文件。
#   "${DOMAIN_ARGS[@]}"  把前面准备好的域名清单展开传进来（一个或多个域名）。
#   --email "$LE_EMAIL"  留一个联系邮箱。作用：证书快到期时对方会发提醒邮件。
#   --agree-tos          表示"我同意服务条款"。
#       为什么要写？不写的话它会停下来等您在屏幕上输入同意，脚本就卡住了。
#   --no-eff-email       表示"不要把我的邮箱共享给电子前沿基金会（一个组织）"。
#       属于隐私选项，不影响证书功能。
#   --redirect            【很实用的一个设置】自动加上"强制跳转"规则：
#       访客如果输入的是普通 http 地址，会被自动引导到安全的 https 地址。
#       效果：不管访客怎么输，最后都停在安全的加密连接上。
#   --non-interactive    表示"全程不要问我问题"，遇到需要确认的地方自动处理。
#       自动化脚本必须加这一项，否则会中途卡住等待输入。

# ------------------------------------------------------------
log "3/4  确认自动续期定时器已开启"
systemctl enable --now certbot.timer >/dev/null 2>&1 || true
# 【这一步很重要，别省】开启"自动续期"的定时任务。
# 拆开读：
#   enable --now = 既设置为"开机自动启动"，又立刻把它启动起来；
#   certbot.timer = 这是一个定时器，会每天自动检查两次证书是否需要续期；
#   >/dev/null 2>&1 || true = 输出不显示、失败也继续（因为它是加分项，失败不影响主功能）。
# 【为什么必须有这一步？】证书 90 天就过期。
# 忘了续期的后果很严重：访客打开网站会看到刺眼的"此网站不安全"警告，很多人会直接关掉。
# 有了这个定时器，证书会在到期前自动续好，您完全不用操心。
systemctl list-timers certbot.timer --no-pager 2>/dev/null | head -3 || true
# 打印这个定时器的状态，让您亲眼确认它确实在运行。
#   list-timers = 列出所有定时任务；--no-pager 表示"不要用分页器显示"（否则要按键翻页）；
#   head -3 = 只取前 3 行，避免输出太长。
ok "自动续期已就绪（每天检查两次，到期前自动续）"

# ------------------------------------------------------------
log "4/4  演练续期流程"
certbot renew --dry-run
# 【演练，强烈建议保留】假装现在证书快到期了，走一遍续期流程，
# 但不会真的更换证书（dry-run = 空跑/试运行）。
# 【为什么值得做？】这样能提前发现"续期会不会失败"。
# 如果现在演练不通过，您立刻就能看到并处理；
# 总比 90 天后手忙脚乱、网站弹安全警告要好得多。
# 看到 "Congratulations, all simulated renewals succeeded" 就是成功了。

echo
ok "HTTPS 配置完成 🎉"
echo "   访问 https://${DOMAIN}/ 应能看到证书有效，且 http 会自动跳到 https。"
# 提示您怎么验收：打开网站看看地址栏有没有小锁图标，
# 再试着输入不带 https 的地址，看是否自动跳转过去。
echo "   查看证书到期时间： certbot certificates"
# 给出一个常用命令：想确认证书还有多久到期，跑这一句即可。
