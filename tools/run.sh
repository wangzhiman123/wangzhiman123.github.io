#!/usr/bin/env bash
#
# ============================================================================
# 【本文件是什么？】
# Run jekyll serve and then launch the site
# 【中文】本机预览脚本——在您自己的电脑上把网站跑起来看看效果
#
# ----------------------------------------------------------------------------
# 一句话概括：这是一个"本地试看"的脚本。
# 它会在您电脑上临时启动一个迷你网页服务器，
# 然后在浏览器里输入一个地址，就能看到网站长什么样——
# 相当于"发布前的预览"，改完文章不用真的上线就能先看效果。
#
# 【为什么要用这个，而不是直接打开 .html 文件？】
# 因为这个网站不是普通的静态网页，它需要"先编译"：
# 您写的 Markdown 文章要先被 Jekyll 转成网页，里面的模板、
# 变量替换也都要跑一遍。所以必须靠这个脚本先做编译，
# 直接双击 .html 文件是看不到正确效果的。
#
# 【用它能看到什么好处？】
#   · 保存文章后会自动重新编译，刷新浏览器就是最新的（不用手动重启）；
#   · 本机预览不会影响线上网站，可以放心乱改乱试。
#
# 用法：
#   在项目根目录执行：
#       bash tools/run.sh
#   然后打开浏览器访问 http://127.0.0.1:4000
#   （127.0.0.1 是本机地址，4000 是默认端口；想停止就在终端按 Ctrl+C）
# ============================================================================

prod=false
# 是否以"正式模式"运行，默认否（false = 开发模式）。

command="bundle exec jekyll s -l"
# 准备要执行的命令。拆开读：
#   bundle exec  —— 用本项目锁定的组件版本来运行，避免版本混乱；
#   jekyll s     —— s 是 serve（提供服务）的简写，意思是"启动预览服务器"；
#   -l           —— l 是 livereload（实时重载）的简写。
#                  效果：您改了文件保存后，浏览器会自动刷新显示最新效果，非常方便。
# 【可DIY修改】想关掉自动刷新可以去掉 -l。

host="127.0.0.1"
# 默认绑定的地址。127.0.0.1 是"本机地址"，
# 意思是"只允许这台电脑自己访问"，别人访问不到——安全又省事。
# 【可DIY修改】如果想用手机连同一个局域网来看，需要改成 0.0.0.0
# 然后用 bash tools/run.sh -H 0.0.0.0 启动，再用电脑的局域网 IP 访问。
# ⚠️ 注意：0.0.0.0 表示允许同一网络内其他人访问，在公共 Wi-Fi 下不建议这么做。

help() {
  # 定义一个"显示用法说明"的小工具，当您加 -h 参数或输错参数时会调用它。
  echo "Usage:"
  echo
  echo "   bash /path/to/run [options]"
  echo
  echo "Options:"
  echo "     -H, --host [HOST]    Host to bind to."
  echo "     -p, --production     Run Jekyll in 'production' mode."
  echo "     -h, --help           Print this help information."
  # 三行英文含义分别是：
  #   -H, --host [地址]  指定监听的地址（默认 127.0.0.1）；
  #   -p, --production   以"正式模式"运行（会启用压缩等优化，效果更接近线上）；
  #   -h, --help         显示这份帮助说明。
}

while (($#)); do
  # 循环处理您输入的所有参数。
  # (($#)) 的意思是"只要还有参数没处理完，就继续循环"（$# 是参数个数）。
  opt="$1"
  # 取出当前第一个参数，存进 opt 变量。
  case $opt in
  # 开始逐个比对、分情况处理。
  -H | --host)
    # 情况一：您想指定访问地址。
    host="$2"
    # 把下一个参数当作地址值取过来。
    shift 2
    # 【为什么是 2？】因为这次消费了两个参数（选项本身 + 它的值），
    # 所以要跳过两个，才能到下一个待处理的参数。
    ;;
  -p | --production)
    # 情况二：您想以正式模式运行。
    prod=true
    shift
    # 这个选项后面没有值，所以只跳过 1 个。
    ;;
  -h | --help)
    # 情况三：您想看帮助说明。
    help
    exit 0
    # 打印帮助后正常退出（0 表示成功）。
    ;;
  *)
    # 情况四：其他情况——也就是输入了不认识的参数。
    echo -e "> Unknown option: '$opt'\n"
    # 提示这个参数不认识。
    help
    exit 1
    # 打印帮助并报错退出，避免带着错误参数继续跑。
    ;;
  esac
done

command="$command -H $host"
# 把前面确定的地址拼进命令里。
# 效果：bundle exec jekyll s -l -H 127.0.0.1

if $prod; then
  command="JEKYLL_ENV=production $command"
fi
# 如果您加了 -p 参数，就在命令前面加上"正式模式"的标记。
# 【作用】正式模式会启用压缩等优化，让预览效果和线上网站一模一样。
# 好处：发文章前可以用它检查"压缩后会不会出问题"
# （比如前面提到的内联脚本不能用 // 注释这个坑，就能在这里提前发现）。

if [ -e /proc/1/cgroup ] && grep -q docker /proc/1/cgroup; then
  command="$command --force_polling"
fi
# 【一段很贴心的兼容处理】
# 先判断"当前是不是在 Docker 容器里运行"（Docker 是一种打包运行环境的技术）：
#   /proc/1/cgroup 是一个记录运行环境信息的系统文件；
#   grep -q docker 是悄悄检查里面有没有 docker 字样。
# 如果在 Docker 里运行，就加上 --force_polling。
# 【为什么需要？】因为 Docker 环境里"文件变动通知机制"经常失效，
# 导致您改了文章保存后，预览不会自动更新。
# --force_polling 的作用是改用"定时去检查文件有没有变"这种笨但可靠的方式，
# 保证自动刷新功能在里面也能正常用。

echo -e "\n> $command\n"
# 把最终要执行的完整命令打印出来。
# 【为什么要打印？】万一启动失败，您可以直接看到"它到底跑了什么命令"，
# 方便复制出来单独排查。
eval "$command"
# 【真正启动】执行这条命令。
# 效果：编译网站并启动预览服务器。
# 然后终端会显示"Server address: http://127.0.0.1:4000"之类的信息，
# 把这个地址复制到浏览器就能看到网站了。
# 想停止：在终端里按 Ctrl + C。
