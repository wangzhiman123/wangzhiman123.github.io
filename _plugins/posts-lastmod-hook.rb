#!/usr/bin/env ruby
#
# ============================================================================
# 【本文件是什么？】
# Check for changed posts（检查文章是否被修改过）
# ----------------------------------------------------------------------------
# 这是一个 Ruby 语言写的「小插件」，Jekyll（网站生成程序）在构建网站时会自动
# 加载并执行它。
#
# 它的作用只有一件事：自动算出每篇文章的「最后修改时间」。
# 效果是：文章页上除了"发布于 2026-10-03"之外，如果这篇内容后来改过，
# 还会自动多显示一行"更新于 2026-10-10"，让读者知道内容有更新。
#
# 为什么要自动算、不手动写？
#   手动写容易忘、也容易写错。而每次提交修改时，Git（版本管理工具，
#   可以理解为"给文件拍快照的记事本"）都会记录下时间，
#   这里就是去问 Git ——"这个文件被改过几次？最后一次是什么时候？"
#
# 只在"确实改过"时才显示更新时间：
#   刚创建的文章只提交过 1 次，不算修改，不显示"更新于"，页面更干净。
#
# 运行流程：
#   Jekyll 构建开始 → 每读到一篇文章就触发下面这段代码 →
#   去问 Git 这个文件改过几次 → 如果超过 1 次 → 把最后修改时间记进文章数据 →
#   _layouts/post.html 发现"有修改时间且和发布时间不同" → 页面上就多显示一行"更新于"。
# ============================================================================

# 注册一个「钩子」。钩子可以理解为"等某个时机到了就自动执行这段代码"。
# :posts 表示"针对文章"；:post_init 表示"每篇文章被读取初始化时"。
# 也就是：每读到一篇文章，就把下面这段跑一遍。
Jekyll::Hooks.register :posts, :post_init do |post|

  # 反引号 ` ` 在 Ruby 里的意思是：把里面的内容当作系统命令去执行，
  # 并把命令的输出结果（文字）拿回来。
  # 这条命令是问 Git："这个文件一共有多少次提交记录？"
  # --count 只输出一个数字；HEAD 表示当前版本；"#{ post.path }" 是这篇文章的文件路径。
  commit_num = `git rev-list --count HEAD "#{ post.path }"`

  # .to_i 把命令返回的"文字型的数字"转成真正的数字，才能拿来比较大小。
  # 大于 1 说明：除了最初创建的那一次提交，后面还改过至少一次。
  if commit_num.to_i > 1
    # 问 Git："这个文件最后一次修改是什么时间？"
    # -1 表示"最近一条记录"；--pretty="%ad" 表示"只输出作者日期"；
    # --date=iso 表示"用国际标准的完整时间格式输出"。
    lastmod_date = `git log -1 --pretty="%ad" --date=iso "#{ post.path }"`
    # 把查到的修改时间存进这篇文章的数据里，字段名固定为 last_modified_at。
    # 存进去之后，页面模板就能读取它来显示"更新于 xxx"。
    post.data['last_modified_at'] = lastmod_date
  end

end
